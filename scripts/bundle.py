"""Bundle the four fixed Quill modules without a third-party build dependency."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent/'docs'
def module(name,imports,exports):
    source=(root/(name+'.js')).read_text()
    source='\n'.join(line for line in source.splitlines() if not line.startswith('import '))
    source=source.replace('export async function ','async function ').replace('export function ','function ').replace('export const ','const ')
    return f'const Quill{name.title()} = (() => {{\n{imports}\n{source}\nreturn {{{exports}}};\n}})();\n'
source='// Generated by scripts/bundle.py. Edit the source modules, then rebuild.\n'
source+=module('core','', 'uuid,validate,union,heads,documents,revise,countWords,escapeXML,fromBackup,backup,zip')
source+=module('storage','const {union,validate}=QuillCore;', 'native,bridge,openStorage,load,put,connectFolder,disconnectFolder,sync,download')
source+=module('export','const {zip,escapeXML:x}=QuillCore;', 'sanitize,plain,manuscriptHTML,epub,docx')
app='\n'.join(line for line in (root/'app.js').read_text().splitlines() if not line.startswith('import '))
source+='(() => {\nconst {uuid,union,heads,documents,revise,countWords,backup,fromBackup,escapeXML:esc}=QuillCore;\nconst storage=QuillStorage;\nconst {sanitize,plain,manuscriptHTML,epub,docx}=QuillExport;\n'+app+'\n})();\n'
(root/'app.bundle.js').write_text(source)
